#!/usr/bin/env bash
# Stage5 Temporal EMA (α=0.5) End-to-End Motion Preservation Ablation — entry driver.
#
# Baseline = the production Stage0-11 run (run_single_video_dataset.sh original
#            flow, already produced under outputs/stage0_17_e2e/stage0_11) whose
#            raw SCRFD bbox is reused (docs/stage5_roi_ablation/baseline_results.json).
# EMA      = inject an experiment-level causal EMA bbox smoothing after Stage5
#            (bbox_smooth_t = 0.5*bbox_raw_t + 0.5*bbox_smooth_{t-1}, [x1,y1,x2,y2],
#            frame 0 = raw, missing detection holds previous box), then re-run
#            Stage10 landmark / Stage11 align / Stage12 FLAME / Stage13 gaze /
#            Stage14 audio / Stage17 fusion through the OFFICIAL production runners.
#
# The two branches are generated by the identical code path (only the bbox
# differs) -> baseline and EMA are fully comparable.  Production code is NOT
# modified; only experiment scripts + outputs under outputs/ema_motion_preservation/.
#
# Usage:
#     bash scripts/run_single_video_dataset_ema_ablation.sh [CLIP_ID] [--smoke]
#
# Env:
#     SRC_BASE   production Stage0-11 base (default outputs/stage0_17_e2e/stage0_11)
set -u

ROOT=/mnt/home/lxs/face_pipeline/Face_Pipeline_V2
cd "$ROOT"

SRC_BASE="${SRC_BASE:-outputs/stage0_17_e2e/stage0_11}"
OUT_BASE=outputs/ema_motion_preservation
DEFAULT_CLIP="CNFACE_00001_BV18Qg96YE1W_000000_scene_0000_clip_0001"

CLIP="${1:-$DEFAULT_CLIP}"
SMOKE=0
[ "${2:-}" = "--smoke" ] && SMOKE=1
[ "${2:-}" = "" ] && [ "${3:-}" = "--smoke" ] && SMOKE=1

mkdir -p logs

echo "==================================================================="
echo "STAGE5 EMA (alpha=0.5) END-TO-END MOTION PRESERVATION ABLATION"
echo "CLIP     = $CLIP"
echo "SRC_BASE = $SRC_BASE   (production Stage0-11 run, baseline flow)"
echo "OUT_BASE = $OUT_BASE"
echo "SMOKE    = $SMOKE"
echo "==================================================================="

# ---- validate production baseline artifacts exist ----
ALIGNED_META="${SRC_BASE}/stage_inputs/${CLIP}_aligned_faces.json"
CLIP_VIDEO="${SRC_BASE}/clips/${CLIP}.mp4"

# Stage14 needs an av_alignment whose aligned audio actually exists.  The
# stage0_11 run's av_alignment may point at a cleaned audio dir; fall back to
# the dataset_validation production run when needed.
_pick_av_alignment() {
    local clip="$1"
    for cand in "${SRC_BASE}/stage_inputs/${clip}_av_alignment.json" \
                "outputs/stage0_17_e2e/dataset_validation/stage_inputs/${clip}_av_alignment.json"; do
        if [ -f "$cand" ]; then
            local ap
            ap=$(/opt/hb/bin/python3 -c "import json; print(json.load(open('$cand')).get('aligned_audio_path') or '')" 2>/dev/null)
            if [ -n "$ap" ] && [ -f "$ap" ]; then
                echo "$cand"
                return 0
            fi
        fi
    done
    return 1
}
AV_ALIGN="$(_pick_av_alignment "$CLIP")" || AV_ALIGN=""
if [ ! -f "$ALIGNED_META" ] || [ ! -f "$CLIP_VIDEO" ] || [ -z "$AV_ALIGN" ]; then
    echo "ERROR: production Stage0-11 artifacts missing for clip ${CLIP}:"
    echo "  aligned_faces : $ALIGNED_META ($([ -f "$ALIGNED_META" ] && echo OK || echo MISSING))"
    echo "  clip video    : $CLIP_VIDEO ($([ -f "$CLIP_VIDEO" ] && echo OK || echo MISSING))"
    echo "  av_alignment  : ${AV_ALIGN:-NONE with valid aligned audio}"
    echo "Run the production flow first (scripts/run_single_video_dataset.sh)."
    exit 1
fi
echo "  AV_ALIGN  = $AV_ALIGN"
if [ ! -f docs/stage5_roi_ablation/baseline_results.json ]; then
    echo "ERROR: baseline SCRFD results missing: docs/stage5_roi_ablation/baseline_results.json"
    exit 1
fi

# =====================================================================
# 1) Stage5 (EMA bbox) / Stage10 (landmark) / Stage11 (align) branches
# =====================================================================
MAX_FRAMES=""
[ "$SMOKE" = "1" ] && MAX_FRAMES="--max-frames 12"
echo "[S5/10/11] generating baseline + ema_alpha05 branches for $CLIP ..."
PYTHONPATH="$ROOT" python3 scripts/stage5_ema_e2e_ablation.py prep \
    --clip "$CLIP" --alpha 0.5 $MAX_FRAMES 2>&1 | tee "logs/ema_e2e_prep_${CLIP}.log"
PREP_RC=${PIPESTATUS[0]}
if [ "$PREP_RC" -ne 0 ]; then
    echo "ERROR: prep failed rc=$PREP_RC (see logs/ema_e2e_prep_${CLIP}.log)"
    exit 1
fi

# =====================================================================
# 2) Stage12 (EMICA, docker) / 13 (gaze) / 14 (audio) / 17 (fusion)
#    for BOTH branches (official production runners, unchanged params)
# =====================================================================
for branch in baseline ema_alpha05; do
    META="${OUT_BASE}/${branch}/stage11/${CLIP}_aligned_faces.json"
    echo "########## branch=$branch clip=$CLIP ##########"

    echo "[S12] $branch starting $(date +%H:%M:%S)"
    docker exec face_pipeline_lxs bash -lc \
        "cd /workspace/Face_Pipeline_V2 && /workspace/emica_ppu_env/bin/python \
            scripts/stage0_17_e2e_stage12.py \
            --input_metadata ${META} \
            --output_dir ${OUT_BASE}/${branch}/stage12_flame \
            --clip_id ${CLIP} --batch_size 8" > "logs/ema_e2e_stage12_${branch}_${CLIP}.log" 2>&1
    echo "[S12] $branch rc=$? $(tail -1 "logs/ema_e2e_stage12_${branch}_${CLIP}.log")"

    echo "[S13] $branch starting $(date +%H:%M:%S)"
    PYTHONPATH="$ROOT" python3 face_pipeline_v2/stages/stage_13_gaze/runner.py \
        --input_metadata "${META}" \
        --output_dir "${OUT_BASE}/${branch}/stage13_gaze" \
        --model_path models/mediapipe/face_landmarker.task \
        --delegate cpu --clip_id "${CLIP}" > "logs/ema_e2e_stage13_${branch}_${CLIP}.log" 2>&1
    echo "[S13] $branch rc=$? $(tail -1 "logs/ema_e2e_stage13_${branch}_${CLIP}.log")"

    # Stage14 audio is bbox-independent -> identical input for both branches
    echo "[S14] $branch starting $(date +%H:%M:%S)"
    PYTHONPATH="$ROOT" python3 face_pipeline_v2/stages/stage_14_audio_feature/runner.py \
        --input_metadata "${AV_ALIGN}" \
        --output_dir "${OUT_BASE}/${branch}/stage14_audio" \
        --model_path models/hubert/chinese-hubert-base \
        --device cpu --fps 25 --clip_id "${CLIP}" > "logs/ema_e2e_stage14_${branch}_${CLIP}.log" 2>&1
    echo "[S14] $branch rc=$? $(tail -1 "logs/ema_e2e_stage14_${branch}_${CLIP}.log")"

    echo "[S17] $branch starting $(date +%H:%M:%S)"
    PYTHONPATH="$ROOT" python3 face_pipeline_v2/stages/stage_17_fusion/runner.py \
        --clip_id "${CLIP}" \
        --flame_dir "${OUT_BASE}/${branch}/stage12_flame" \
        --gaze_dir "${OUT_BASE}/${branch}/stage13_gaze" \
        --audio_dir "${OUT_BASE}/${branch}/stage14_audio" \
        --output_dir "${OUT_BASE}/${branch}/stage17_fusion" \
        --fps 25 > "logs/ema_e2e_stage17_${branch}_${CLIP}.log" 2>&1
    echo "[S17] $branch rc=$? $(tail -1 "logs/ema_e2e_stage17_${branch}_${CLIP}.log")"
done

# =====================================================================
# 3) comparison metrics + overlay videos + report
# =====================================================================
echo "[ANALYZE] starting $(date +%H:%M:%S)"
PYTHONPATH="$ROOT" python3 scripts/stage5_ema_e2e_ablation.py analyze \
    2>&1 | tee "logs/ema_e2e_analyze_${CLIP}.log"
ANA_RC=${PIPESTATUS[0]}

echo "==================================================================="
echo "ALL DONE $(date +%H:%M:%S) | prep rc=$PREP_RC | analyze rc=$ANA_RC"
echo "  OUT_BASE = $OUT_BASE"
echo "  REPORT   = docs/Stage5_EMA_Motion_Preservation_Report.md"
echo "==================================================================="
exit $ANA_RC

