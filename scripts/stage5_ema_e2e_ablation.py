def _h264_ffmpeg(raw_path: Path, out_path: Path) -> None:
    cmd = [str(FFMPEG), "-y", "-i", str(raw_path),
           "-c:v", "libx264", "-preset", "fast", "-crf", "20",
           "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", str(out_path)]
    subprocess.run(cmd, check=True, capture_output=True)
    raw_path.unlink(missing_ok=True)


def _draw_box(img: np.ndarray, bbox, color, thickness: int = 3) -> None:
    x1, y1, x2, y2 = (int(round(v)) for v in bbox)
    cv2.rectangle(img, (x1, y1), (x2, y2), color, thickness)


def _label(img: np.ndarray, text: str, x: int, y: int, color) -> None:
    (tw, th), _ = cv2.getTextSize(text, _FONT, 0.8, 2)
    cv2.rectangle(img, (x, y - th - 8), (x + tw + 8, y + 4), BLACK, -1)
    cv2.putText(img, text, (x + 4, y), _FONT, 0.8, color, 2, cv2.LINE_AA)


def render_overlays(clip_id: str, skip: bool = False) -> List[str]:
    """§4 overlay videos: bbox + 106 landmarks + frame index (same fps/resolution).

    Writes baseline_bbox_landmark_overlay.mp4 and
    ema_alpha05_bbox_landmark_overlay.mp4 into outputs/ema_motion_preservation/videos/.
    """
    VIDEO_DIR.mkdir(parents=True, exist_ok=True)
    video_path = SRC_BASE / "clips" / f"{clip_id}.mp4"
    specs = [
        ("baseline_bbox_landmark_overlay.mp4", "baseline",
         "Baseline  SCRFD raw bbox + 106 lmk", GREEN, None),
        ("ema_alpha05_bbox_landmark_overlay.mp4", "ema_alpha05",
         "EMA  alpha=0.5  bbox + 106 lmk", ORANGE, ALPHA),
    ]
    produced: List[str] = []
    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise RuntimeError(f"cannot open clip video: {video_path}")
    W = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS) or FPS

    for out_name, branch, title, color, alpha in specs:
        if skip:
            print(f"[video] skipped {out_name} (--skip-videos)")
            continue
        recs = _branch_boxes(branch)
        lms = _branch_landmarks(branch)
        n = len(recs)
        raw_tmp = VIDEO_DIR / ("_raw_" + out_name)
        fourcc = cv2.VideoWriter_fourcc(*"mp4v")
        writer = cv2.VideoWriter(str(raw_tmp), fourcc, fps, (W, H))
        if not writer.isOpened():
            raise RuntimeError(f"cannot create video writer: {raw_tmp}")
        cap.set(cv2.CAP_PROP_POS_FRAMES, 0)
        for i in range(n):
            ok, frame = cap.read()
            if not ok:
                break
            rec = recs[i]
            bbox = rec.get("bbox")
            if bbox:
                _draw_box(frame, bbox, color, 3)
                if alpha is not None and rec.get("raw_bbox"):
                    _draw_box(frame, rec["raw_bbox"], BLUE, 1)  # faint raw SCRFD
            lr = lms[i]
            lmf = lr.get("landmarks_106")
            if lmf:
                pts = np.asarray(lmf).reshape(106, 2)
                for (px, py) in pts:
                    cv2.circle(frame, (int(round(px)), int(round(py))), 2, WHITE, -1)
            tag = f"{title}  |  frame {int(rec['frame_id']):03d}"
            if rec.get("confidence") is not None:
                tag += f"  |  conf {rec['confidence']:.3f}"
            _label(frame, tag, 12, 30, WHITE)
            writer.write(frame)
        writer.release()
        final = VIDEO_DIR / out_name
        print(f"[video] rendering {out_name} ...", flush=True)
        _h264_ffmpeg(raw_tmp, final)
        produced.append(str(final))
        print(f"[video] wrote {final}")
    cap.release()
    return produced


