def analyze(skip_videos: bool = False) -> Dict[str, Any]:
    """Full comparison: bbox/landmark + FLAME + Stage17 + videos + report."""
    clip_id = _clip()
    print(f"[analyze] clip={clip_id}", flush=True)

    bbox_comp = compare_bbox_landmark(clip_id)
    print(f"[analyze] bbox: center jitter "
          f"{bbox_comp['baseline']['bbox_center_jitter']['center_jitter_mean']:.3f} -> "
          f"{bbox_comp['ema_alpha05']['bbox_center_jitter']['center_jitter_mean']:.3f} px "
          f"({bbox_comp['deltas']['center_jitter_delta_pct']:+.1f}%)", flush=True)

    flame_comp = compare_flame(clip_id)
    ratios = flame_comp["motion_energy_ratios"]
    print(f"[analyze] ratios: expr={ratios['expression_energy_ratio']:.3f} "
          f"head={ratios['head_motion_ratio']:.3f} jaw={ratios['jaw_motion_ratio']:.3f}",
          flush=True)

    fidelity = compare_production_fidelity(clip_id)
    if fidelity.get("available"):
        fd = fidelity["max_abs_diff_vs_production"]
        print(f"[analyze] production fidelity (baseline branch vs production Stage12): "
              f"expr={fd['expression']:.3e} head={fd['head_pose']:.3e} "
              f"jaw={fd['jaw_pose']:.3e}", flush=True)

    s17 = verify_stage17(clip_id)
    for branch in BRANCHES:
        print(f"[analyze] stage17 {branch}: "
              f"visual={s17[branch]['visual_feature_shape']} "
              f"layout_ok={s17[branch]['layout_ok']}", flush=True)

    videos = render_overlays(clip_id, skip=skip_videos)

    report = build_report(clip_id, bbox_comp, flame_comp, s17, videos, fidelity)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"[report] wrote {REPORT_PATH}")

    metrics = {
        "clip_id": clip_id,
        "alpha": ALPHA,
        "bbox_landmark": bbox_comp,
        "flame": flame_comp,
        "stage17": s17,
        "production_fidelity": fidelity,
        "report": _to_rel(REPORT_PATH),
    }
    _write_json(COMPARISON_DIR / "ablation_metrics.json", metrics)
    return metrics


def _parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_prep = sub.add_parser("prep", help="generate Stage5/10/11 for both branches")
    p_prep.add_argument("--clip", default=DEFAULT_CLIP)
    p_prep.add_argument("--alpha", type=float, default=ALPHA)
    p_prep.add_argument("--max-frames", type=int, default=None,
                        help="limit frames (smoke test)")
    p_prep.set_defaults(func=cmd_prep)

    p_ana = sub.add_parser("analyze", help="comparison + videos + report")
    p_ana.add_argument("--skip-videos", action="store_true")
    p_ana.set_defaults(func=cmd_analyze)

    return ap.parse_args(argv)


def cmd_prep(args: argparse.Namespace) -> int:
    print(f"[prep] clip={args.clip} alpha={args.alpha} "
          f"max_frames={args.max_frames or 'all'}", flush=True)
    r = prep_clip(args.clip, args.alpha, args.max_frames)
    for branch in BRANCHES:
        print(f"[prep] {branch}: n={r[branch]['n']} "
              f"aligned={r[branch]['n_aligned']} "
              f"landmarks={r[branch]['n_landmarks']} "
              f"landmark_jitter={r[branch]['landmark_jitter_mean']:.3f}px "
              f"center_jitter={r[branch]['center_jitter_mean']:.3f}px", flush=True)
    return 0


def cmd_analyze(args: argparse.Namespace) -> int:
    analyze(skip_videos=args.skip_videos)
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s [%(levelname)s] %(message)s")
    args = _parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
