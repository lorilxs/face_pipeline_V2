_landmark_model: Optional[InsightFaceLandmarkWrapper] = None


def _get_landmark_model() -> InsightFaceLandmarkWrapper:
    global _landmark_model
    if _landmark_model is None:
        _landmark_model = InsightFaceLandmarkWrapper(str(LANDMARK_MODEL), device="cpu")
        _landmark_model.load()
    return _landmark_model


def extract_106_landmarks(
    frame: np.ndarray,
    bbox: Tuple[float, float, float, float],
    W: int,
    H: int,
) -> Optional[np.ndarray]:
    """Mirror production Stage10: expand bbox (ratio 2.0), crop, 2d106det.

    Byte-for-byte identical to the Stage5 ROI / bbox-EMA ablations' extraction
    (int()-truncated crop indices, float expanded origin) so the baseline
    landmark numbers chain across all experiments (baseline jitter = 1.752 px).

    Returns the (106, 2) landmark array in *full-frame* pixel coordinates, or
    None if the crop is degenerate / detection fails.
    """
    exp = expand_bbox(list(bbox), W, H, PRODUCTION_EXPAND)
    ex1, ey1, ex2, ey2 = exp
    x1, y1, x2, y2 = int(ex1), int(ey1), int(ex2), int(ey2)
    if x2 <= x1 or y2 <= y1:
        return None
    crop = frame[y1:y2, x1:x2]
    if crop.size == 0:
        return None
    try:
        lm_crop = _get_landmark_model().predict(crop)
    except Exception:
        return None
    lms = np.asarray(lm_crop, dtype=np.float64).reshape(-1, 2).copy()
    lms[:, 0] += ex1
    lms[:, 1] += ey1
    return lms


