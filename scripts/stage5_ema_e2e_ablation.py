def _load_baseline(path: Path) -> List[Dict[str, Any]]:
    """Load the reused baseline SCRFD per-frame results (clip-local frame_id)."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    kept: List[Dict[str, Any]] = []
    for f in data["frames"]:
        kept.append({
            "frame_id": int(f["frame_id"]),
            "bbox": list(f["bbox"]) if f.get("bbox") else None,
            "confidence": float(f.get("confidence", 0.0)),
        })
    return kept


def bbox_center(bbox: Tuple[float, float, float, float]) -> Tuple[float, float]:
    return ((bbox[0] + bbox[2]) / 2.0, (bbox[1] + bbox[3]) / 2.0)


def _transitions(
    boxes: List[Optional[Tuple[float, float, float, float]]],
) -> List[Tuple[int, int, Tuple[float, float, float, float],
                Tuple[float, float, float, float]]]:
    """Consecutive (prev_idx, cur_idx, prev_bbox, cur_bbox) pairs, both boxes set."""
    trans = []
    prev_i, prev_b = None, None
    for i, b in enumerate(boxes):
        if b is None:
            prev_i, prev_b = None, None
            continue
        if prev_b is not None and prev_i is not None:
            trans.append((prev_i, i, prev_b, b))
        prev_i, prev_b = i, b
    return trans


def _trans_delta(t) -> float:
    _, _, a, b = t
    return float(math.hypot(*np.subtract(bbox_center(a), bbox_center(b))))


def _mean_std_max(vals: List[float]) -> Tuple[float, float, float]:
    if not vals:
        return 0.0, 0.0, 0.0
    a = np.asarray(vals, dtype=np.float64)
    return float(a.mean()), float(a.std(ddof=0)), float(a.max())


def center_jitter_metrics(boxes) -> Dict[str, Any]:
    dists = [_trans_delta(t) for t in _transitions(boxes)]
    m, s, mx = _mean_std_max(dists)
    return {"center_jitter_mean": m, "center_jitter_std": s, "max_jump": mx,
            "n_transitions": len(dists)}


def scale_jitter_metrics(boxes) -> Dict[str, Any]:
    wdiffs, hdiffs = [], []
    for _, _, a, b in _transitions(boxes):
        wdiffs.append(abs((b[2] - b[0]) - (a[2] - a[0])))
        hdiffs.append(abs((b[3] - b[1]) - (a[3] - a[1])))
    return {"width_jitter": float(np.mean(wdiffs)),
            "height_jitter": float(np.mean(hdiffs))}


def isolated_outliers(boxes, threshold: float = OUTLIER_PX) -> Dict[str, Any]:
    """Isolated spikes: current delta > threshold, surrounding deltas normal."""
    trans = _transitions(boxes)
    frames: List[int] = []
    for k, t in enumerate(trans):
        cur = _trans_delta(t)
        if cur <= threshold:
            continue
        prev_ok = k == 0 or _trans_delta(trans[k - 1]) <= threshold
        next_ok = k == len(trans) - 1 or _trans_delta(trans[k + 1]) <= threshold
        if prev_ok and next_ok:
            frames.append(int(t[1]))
    return {"outlier_count": len(frames), "outlier_frames": frames,
            "threshold_px": threshold}


def landmark_jitter_metrics(
    lms_seq: List[Optional[np.ndarray]],
) -> Dict[str, Any]:
    """Per-transition mean point distance over 106 landmarks."""
    jumps: List[float] = []
    prev: Optional[np.ndarray] = None
    for lms in lms_seq:
        if lms is None:
            prev = None
            continue
        if prev is not None and prev.shape == lms.shape:
            jumps.append(float(np.mean(np.linalg.norm(lms - prev, axis=1))))
        prev = lms
    m, s, mx = _mean_std_max(jumps)
    if s > 1e-6:
        out = sum(1 for j in jumps if j > m + 3.0 * s)
    else:
        out = 0
    return {"landmark_jitter_mean": m, "landmark_max_jump": mx,
            "landmark_outlier_count": out}


