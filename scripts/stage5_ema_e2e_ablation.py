def prep_branch(
    branch: str,
    clip_id: str,
    video_path: Path,
    src_recs: List[Dict[str, Any]],
    boxes_raw: List[Optional[Tuple[float, float, float, float]]],
    boxes: List[Optional[Tuple[float, float, float, float]]],
    confs: List[float],
    alpha: Optional[float],
) -> Dict[str, Any]:
    """Generate one branch's Stage5 (bbox/crops), Stage10 (landmarks) & Stage11
    (aligned faces + *_aligned_faces.json) artifacts.

    ``boxes`` == raw SCRFD boxes for ``baseline``, EMA-smoothed for ``ema_alpha05``.
    """
    branch_dir = OUT_BASE / branch
    stage5_dir = branch_dir / "stage5"
    stage10_dir = branch_dir / "stage10"
    stage11_dir = branch_dir / "stage11"
    aligned_dir = stage11_dir / "aligned_faces"

    n = len(src_recs)
    assert n == len(boxes), (n, len(boxes))

    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise RuntimeError(f"cannot open clip video: {video_path}")
    W = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS)
    print(f"[prep:{branch}] clip={clip_id} n={n} video={W}x{H}@{fps:.2f}", flush=True)

    stage5_frames: List[Dict[str, Any]] = []
    lm_records: List[Dict[str, Any]] = []
    landmark_seqs: List[Optional[np.ndarray]] = []
    t0 = time.time()

    for i in range(n):
        ok, frame = cap.read()
        if not ok:
            print(f"[prep:{branch}] WARNING: only {i} frames available in clip", flush=True)
            n = i
            break
        src = src_recs[i]
        b = boxes[i]
        conf = confs[i]

        # ---- Stage5: expand bbox + save native-resolution crop (production crop) ----
        exp = expand_bbox(list(b), W, H, PRODUCTION_EXPAND)
        x1, y1, x2, y2 = int(exp[0]), int(exp[1]), int(exp[2]), int(exp[3])
        crop = frame[y1:y2, x1:x2] if (x2 > x1 and y2 > y1) else None
        crop_path = stage5_dir / "crops" / f"frame_{i:06d}_face_000.jpg"
        if crop is not None and crop.size:
            crop_path.parent.mkdir(parents=True, exist_ok=True)
            cv2.imwrite(str(crop_path), crop)

        # ---- Stage10: 2d106det on the crop -> frame coordinates ----
        lms = extract_106_landmarks(frame, b, W, H)
        lm_rec = {
            "frame_id": i,
            "frame_index": int(src["frame_index"]),
            "timestamp": float(src["timestamp"]),
            "clip_id": clip_id,
            "face_id": src["face_id"],
            "bbox": list(b) if b else None,
            "expanded_bbox": list(exp),
            "confidence": conf,
            "landmarks_106": ([float(v) for v in lms.flatten()] if lms is not None else None),
        }
        lm_records.append(lm_rec)
        landmark_seqs.append(lms)

        stage5_frames.append({
            "frame_id": i,
            "frame_index": int(src["frame_index"]),
            "timestamp": float(src["timestamp"]),
            "bbox": list(b) if b else None,
            "expanded_bbox": list(exp),
            "confidence": conf,
        })
        if branch != "baseline":
            stage5_frames[-1]["raw_bbox"] = (
                list(boxes_raw[i]) if boxes_raw[i] is not None else None)

        if (i + 1) % 50 == 0:
            print(f"  [prep:{branch}] frame {i + 1} elapsed {time.time() - t0:.0f}s",
                  flush=True)
    cap.release()
    print(f"[prep:{branch}] {n} frames processed in {time.time() - t0:.1f}s", flush=True)

    # ---- Stage5 bbox asset ----
    _write_json(stage5_dir / "bboxes.json", {
        "experiment": {
            "name": "stage5_ema_e2e_motion_preservation",
            "clip": clip_id,
            "branch": branch,
            "alpha": (None if branch == "baseline" else alpha),
            "fps": FPS,
            "expand_ratio": PRODUCTION_EXPAND,
            "ema_formula": "bbox_smooth_t = alpha*bbox_raw_t + (1-alpha)*bbox_smooth_{t-1}",
            "baseline_source": _to_rel(BASELINE_SOURCE),
            "video": _to_rel(video_path),
        },
        "frames": stage5_frames,
    })

    # ---- Stage10 landmark asset ----
    _write_json(stage10_dir / "landmarks.json", {
        "clip_id": clip_id, "branch": branch, "frames": lm_records,
    })

    # ---- Stage11: production align_faces -> aligned crops + affine matrix ----
    face_infos: List[FrameInfo] = []
    for i in range(n):
        src = src_recs[i]
        fi = FaceInfo(
            frame_index=int(src["frame_index"]),
            face_id=src["face_id"],
            bbox=tuple(boxes[i]) if boxes[i] is not None else (0.0, 0.0, 0.0, 0.0),
            landmark_5=(),
            confidence=confs[i],
            face_crop_path=stage5_dir / "crops" / f"frame_{i:06d}_face_000.jpg",
            track_id=None,
            expanded_bbox=tuple(lm_records[i]["expanded_bbox"]),
        )
        face_infos.append(FrameInfo(
            frame_index=int(src["frame_index"]),
            clip_id=clip_id,
            timestamp=float(src["timestamp"]),
            image_path=Path(""),
            faces=(fi,),
        ))
    sequence = FaceSequence(
        clip_id=clip_id,
        video_id=clip_id.split("_scene", 1)[0],
        frames=tuple(face_infos),
        identity_result=None,
        stability_result=None,
    )

    landmark_infos: List[LandmarkInfo] = []
    for i in range(n):
        src = src_recs[i]
        lms = lm_records[i]["landmarks_106"]
        if lms is None:
            continue
        landmark_infos.append(LandmarkInfo(
            clip_id=clip_id,
            frame_index=int(src["frame_index"]),
            face_id=src["face_id"],
            timestamp=float(src["timestamp"]),
            landmarks_106=tuple(lms),
            image_width=W,
            image_height=H,
        ))

    # Alignment template resolved from the production config (identical output).
    import yaml  # noqa: PLC0415
    cfg = yaml.safe_load(
        (_PROJECT_ROOT / "configs/config_dataset_mode.yaml").read_text(encoding="utf-8"))
    template_params = resolve_alignment_template(cfg.get("alignment", {}))
    eyes_template = template_params["eyes"]
    print(f"[prep:{branch}] alignment template: "
          f"eye_distance={template_params['eye_distance']:.3f} "
          f"eye_center_y={template_params['eye_center_y']:.3f} "
          f"scale_factor={template_params['scale_factor']:.3f}", flush=True)

    aligned = align_faces(
        landmarks=landmark_infos,
        face_sequences=[sequence],
        output_dir=aligned_dir,
        output_resolution=(ALIGN_RES, ALIGN_RES),
        save_images=True,
        logger=_log,
        eye_template=eyes_template,
    )
    aligned_sorted = sorted(aligned, key=lambda a: int(a.frame_index))
    recs = [{
        "clip_id": a.clip_id,
        "frame_index": int(a.frame_index),
        "face_id": a.face_id,
        "timestamp": float(a.timestamp),
        "aligned_face_path": _to_rel(a.aligned_face_path),
        "affine_matrix": list(a.affine_matrix),
        "original_image_size": list(a.original_image_size),
        "aligned_resolution": list(a.aligned_resolution),
    } for a in aligned_sorted]
    _write_json(stage11_dir / f"{clip_id}_aligned_faces.json", recs)

    return {
        "branch": branch, "n": n,
        "n_aligned": len(recs),
        "n_landmarks": sum(1 for r in lm_records if r["landmarks_106"]),
        "landmark_jitter_mean": landmark_jitter_metrics(landmark_seqs)["landmark_jitter_mean"],
        "center_jitter_mean": center_jitter_metrics(boxes)["center_jitter_mean"],
        "aligned_metadata": _to_rel(stage11_dir / f"{clip_id}_aligned_faces.json"),
    }


def prep_clip(clip_id: str, alpha: float, max_frames: Optional[int]) -> Dict[str, Any]:
    """Generate both branches' Stage5/10/11 artifacts for one clip."""
    video_path = SRC_BASE / "clips" / f"{clip_id}.mp4"
    if not video_path.exists():
        raise RuntimeError(f"clip video not found: {video_path}")
    src_recs = _load_production_aligned_meta(clip_id)

    base = _load_baseline(BASELINE_SOURCE)
    if max_frames:
        base = base[:max_frames]
        src_recs = src_recs[:max_frames]
    boxes_raw: List[Optional[Tuple[float, float, float, float]]] = [
        tuple(f["bbox"]) if f.get("bbox") else None for f in base]
    confs = [float(f.get("confidence", 0.0)) for f in base]
    ema_boxes = ema_smooth(boxes_raw, alpha)
    assert len(boxes_raw) == len(src_recs), (len(boxes_raw), len(src_recs))

    results: Dict[str, Any] = {"clip_id": clip_id, "alpha": alpha}
    for branch in BRANCHES:
        boxes = boxes_raw if branch == "baseline" else ema_boxes
        r = prep_branch(
            branch=branch, clip_id=clip_id, video_path=video_path,
            src_recs=src_recs, boxes_raw=boxes_raw, boxes=boxes,
            confs=confs, alpha=(None if branch == "baseline" else alpha),
        )
        results[branch] = r
    _write_json(COMPARISON_DIR / "prep_summary.json", results)
    return results


