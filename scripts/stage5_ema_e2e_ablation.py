def verify_stage17(clip_id: str) -> Dict[str, Any]:
    """§3 Stage17 comparison: visual_feature shape + layout + block cross-checks.

    visual_feature [T,112] layout (task spec §3):
        expression [0,100]  head_pose [100,103]  jaw_pose [103,106]  gaze [106,112]
    Each block is cross-checked against its source stage (12 flame / 13 gaze).
    """
    out: Dict[str, Any] = {"layout": {k: list(v) for k, v in LAYOUT.items()}}
    for branch in BRANCHES:
        ts = np.load(OUT_BASE / branch / "stage17_fusion" / clip_id / "training_sample.npz")
        vf = ts["visual_feature"]
        af = ts["audio_feature"]
        T = vf.shape[0]
        blocks = {k: vf[:, v[0]:v[1]] for k, v in LAYOUT.items()}

        flame = _branch_flame(branch, clip_id)
        gaze = _branch_gaze(branch, clip_id)
        # align source arrays to the training-sample time axis (same T)
        maxdiff = {
            "expression": float(np.max(np.abs(blocks["expression"] - flame["expression_code"][:T]))),
            "head_pose": float(np.max(np.abs(blocks["head_pose"] - flame["head_pose"][:T]))),
            "jaw_pose": float(np.max(np.abs(blocks["jaw_pose"] - flame["jaw_pose"][:T]))),
            "gaze": float(np.max(np.abs(blocks["gaze"] - gaze[:T]))),
        }
        out[branch] = {
            "visual_feature_shape": list(vf.shape),
            "audio_feature_shape": list(af.shape),
            "valid_length": int(ts["valid_length"]),
            "layout_ok": bool(
                list(vf.shape) == [T, 112] and list(af.shape) == [T, 768]
                and all(maxdiff[k] < 1e-4 for k in maxdiff)),
            "block_max_abs_diff_vs_source": maxdiff,
        }
    return out


