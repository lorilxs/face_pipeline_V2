def recommend(bbox_comp: Dict[str, Any], flame_comp: Dict[str, Any]) -> Dict[str, Any]:
    """Decision helper: does EMA keep downstream dynamics while stabilising bbox?"""
    bj = bbox_comp["baseline"]["bbox_center_jitter"]["center_jitter_mean"]
    ej = bbox_comp["ema_alpha05"]["bbox_center_jitter"]["center_jitter_mean"]
    ratios = flame_comp["motion_energy_ratios"]
    q1 = ej < bj
    # downstream dynamics preserved within ±10% of baseline motion energy
    q2 = (ratios["expression_energy_ratio"] is not None
          and 0.90 <= ratios["expression_energy_ratio"] <= 1.10)
    q3 = (ratios["head_motion_ratio"] is not None
          and 0.90 <= ratios["head_motion_ratio"] <= 1.10)
    q4 = (ratios["jaw_motion_ratio"] is not None
          and 0.90 <= ratios["jaw_motion_ratio"] <= 1.10)
    rec = "推荐进入生产" if (q1 and q2 and q3 and q4) else "暂不推荐"
    return {"q1_bbox_reduced": q1, "q2_expression_ok": q2, "q3_head_ok": q3,
            "q4_jaw_ok": q4, "recommendation": rec}



