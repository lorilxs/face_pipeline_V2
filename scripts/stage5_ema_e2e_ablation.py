def _velocity(x: np.ndarray) -> float:
    d = np.diff(np.asarray(x, dtype=np.float64), axis=0)
    return float(np.mean(np.linalg.norm(d, axis=1))) if len(d) else 0.0


def _motion_energy(x: np.ndarray) -> float:
    d = np.diff(np.asarray(x, dtype=np.float64), axis=0)
    return float(np.sum(d ** 2)) if len(d) else 0.0


def _max_delta(x: np.ndarray) -> float:
    d = np.diff(np.asarray(x, dtype=np.float64), axis=0)
    return float(np.max(np.linalg.norm(d, axis=1))) if len(d) else 0.0


def flame_metrics(expr: np.ndarray, head: np.ndarray, jaw: np.ndarray) -> Dict[str, Any]:
    """§2 FLAME comparison: expression / head_pose / jaw_pose dynamics."""
    return {
        "expression": {
            "velocity": _velocity(expr),           # mean frame-to-frame L2
            "std": float(np.std(expr)),
            "max_delta": _max_delta(expr),
            "motion_energy": _motion_energy(expr),
        },
        "head_pose": {
            "velocity": _velocity(head),           # rotation velocity
            "std": float(np.std(head)),
            "max_delta": _max_delta(head),
            "motion_energy": _motion_energy(head),
        },
        "jaw_pose": {
            "amplitude": float(np.std(jaw)),       # amplitude = temporal std
            "velocity": _velocity(jaw),
            "range": float(np.mean(np.ptp(jaw, axis=0))),   # mean per-dim range
            "motion_energy": _motion_energy(jaw),
        },
    }


def compare_flame(clip_id: str) -> Dict[str, Any]:
    """§2 FLAME comparison between the two branches + motion-energy ratios."""
    flame = {b: _branch_flame(b, clip_id) for b in BRANCHES}
    m = {b: flame_metrics(flame[b]["expression_code"], flame[b]["head_pose"],
                          flame[b]["jaw_pose"]) for b in BRANCHES}
    base, ema = m["baseline"], m["ema_alpha05"]
    ratios = {
        "expression_energy_ratio": (
            ema["expression"]["motion_energy"] / base["expression"]["motion_energy"]
            if base["expression"]["motion_energy"] else None),
        "head_motion_ratio": (
            ema["head_pose"]["motion_energy"] / base["head_pose"]["motion_energy"]
            if base["head_pose"]["motion_energy"] else None),
        "jaw_motion_ratio": (
            ema["jaw_pose"]["motion_energy"] / base["jaw_pose"]["motion_energy"]
            if base["jaw_pose"]["motion_energy"] else None),
    }
    return {"metrics": m, "motion_energy_ratios": ratios}


def compare_production_fidelity(clip_id: str) -> Dict[str, Any]:
    """Fidelity check: my regenerated *baseline* branch vs the PRODUCTION Stage12.

    Proves the experiment baseline branch is close to the production Stage5→12
    chain, i.e. the EMA bbox is the only variable in the EMA vs baseline delta.

    Uses ``outputs/stage12_flame/`` (the ``run_single_video_dataset.sh``
    production output, jaw_fusion_lambda=1.0 — same as this experiment) so the
    comparison is not confounded by the legacy lambda=0.6 e2e runs.
    """
    candidates = [
        _PROJECT_ROOT / "outputs/stage12_flame",
        _PROJECT_ROOT / "outputs/stage0_17_e2e/dataset_validation/stage12_flame",
        _PROJECT_ROOT / "outputs/stage0_17_e2e/stage12_flame",
    ]
    prod_npz = None
    for base in candidates:
        p = base / clip_id / "flame_features.npz"
        if p.exists():
            m = base / clip_id / "flame_metadata.json"
            lam = None
            if m.exists():
                try:
                    lam = json.loads(m.read_text(encoding="utf-8")).get("jaw_fusion_lambda")
                except Exception:
                    lam = None
            # prefer the run_single_video_dataset.sh production output (lambda=1.0)
            if lam is None or abs(float(lam) - 1.0) < 1e-6:
                prod_npz = np.load(p)
                break
    if prod_npz is None:
        return {"available": False}
    bz = _branch_flame("baseline", clip_id)
    T = min(prod_npz["expression_code"].shape[0], bz["expression_code"].shape[0])
    return {
        "available": True,
        "max_abs_diff_vs_production": {
            "expression": float(np.max(np.abs(
                prod_npz["expression_code"][:T] - bz["expression_code"][:T]))),
            "head_pose": float(np.max(np.abs(
                prod_npz["head_pose"][:T] - bz["head_pose"][:T]))),
            "jaw_pose": float(np.max(np.abs(
                prod_npz["jaw_pose"][:T] - bz["jaw_pose"][:T]))),
        },
    }


